/** What still stands between a player and a table, or null once it is theirs to play. */
export function venueLock(
  u: { xp?: number; venueWins?: Record<string, number> },
  v: (typeof venues)[number],
) {
  if (levelOf(u.xp || 0) < v.level) return `Level ${v.level} required`;
  const prev = venues[venues.indexOf(v) - 1];
  const won = (prev && u.venueWins?.[prev.id]) || 0;
  return prev && won < v.wins
    ? `Win ${v.wins} in ${prev.name} · ${won}/${v.wins}`
    : null;
}
